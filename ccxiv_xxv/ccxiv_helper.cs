using System;
//----------------------------------------------------------
using ccxiv;
//----------------------------------------------------------
namespace ccxiv_xxv {
    //----------------------------------------------------------
    public static class xxv {
        //----------------------------------------------------------
        public static string _workpath = @"C:\WORKSHOP\Dropbox\PROJ\xxv";
        public static string _datapath = _workpath;
        public static string _userpath = _workpath;
        //----------------------------------------------------------
        private static int _uid = 0;
        private static string _maintag = "";
        private static Dictionary<int,ccxiv_xxv_log> _logformats = new();
        public static int _color_rotate = 8;
        //----------------------------------------------------------
        public static int uid() { _uid++; return (_uid); }
        //----------------------------------------------------------
        public static void maintag(string maintag_) { _maintag=maintag_; }
        //----------------------------------------------------------
        public static void fenter(string funcname_) {
            //----------------------------------------------------------
            int tid = System.Environment.CurrentManagedThreadId;
            if(!_logformats.ContainsKey(tid)) { _logformats[tid]=new(); }
            ccxiv_xxv_log logformat = new(_logformats[tid], _maintag, funcname_);
            _logformats[tid]=logformat;
            //----------------------------------------------------------
            //log("┌──────────────────────────────────────────────┐");
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void fenter(string classname_, string funcname_) {
            //----------------------------------------------------------
            fenter(classname_+"::"+funcname_);
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void fexit() {
            //----------------------------------------------------------
            //log("└──────────────────────────────────────────────┘");
            //----------------------------------------------------------
            int tid = System.Environment.CurrentManagedThreadId;
            if(_logformats[tid]!=null)        
                if(_logformats[tid]._prev!=null)
                    _logformats[tid]=_logformats[tid]._prev;
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void linebreak() {
            //----------------------------------------------------------
            log("─────────────────────────────────────────────");
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void exception(string text_, Exception exception_) {
            //----------------------------------------------------------
            int tid = System.Environment.CurrentManagedThreadId;
            _logformats[tid]=new();
            //----------------------------------------------------------
            log(text_+" : exception={"+exception_.ToString()+"}");
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void warn(bool warn_, string text_) {
            //----------------------------------------------------------
            if(warn_) { log("WARN "+text_); }
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void warn(bool warn_, string text_, object var_) {
            //----------------------------------------------------------
            if(warn_) { log("WARN "+text_, var_); }
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void log(string name_, object var_) {
            //----------------------------------------------------------
            if(var_==null) {
                say(name_+"={null}");
                } else { say(name_+"={"+var_.ToString()+"}"); }
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void log(string text_) {
            //----------------------------------------------------------
            say(text_);
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void say(string text_) {
            //----------------------------------------------------------
            int tid = System.Environment.CurrentManagedThreadId;
            ccxiv_xxv_log logformat=_logformats[tid];
            //if(logformat==null) { logformat=new(); _logformats[tid]=logformat; };
            //----------------------------------------------------------
            string str = logformat.format(text_);
            //----------------------------------------------------------
            Console.ForegroundColor=logformat._color;
            say_console(str);
            //Console.ForegroundColor=ConsoleColor.White;
            //----------------------------------------------------------
            say_file(str);
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        private static void say_console(string text_) {
            //----------------------------------------------------------
            Console.WriteLine(text_);
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        private static void say_file(string text_) {
            //----------------------------------------------------------
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static byte[] fullread(string fn_) {
            //----------------------------------------------------------
            log("FULLREAD fn_",fn_);
            //----------------------------------------------------------
            byte[] buffer;
            using(FileStream stream = File.Open(fn_, FileMode.Open)) {
                //----------------------------------------------------------
                int length = (int)stream.Length;
                buffer=new byte[length];
                stream.Read(buffer, 0,length);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            return (buffer);
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
