using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Text;
using System.Threading.Tasks;
//----------------------------------------------------------
using ccxiv;
//----------------------------------------------------------
namespace ccxiv_xxv {
    //----------------------------------------------------------
    public class ccxiv_xxv_root_list<TYPE> : IDisposable {
        //----------------------------------------------------------
        public List<TYPE> _list = new();
        public bool _disposed = false;
        //----------------------------------------------------------
        public ccxiv_xxv_root_list() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_root_list::new");
            //----------------------------------------------------------
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            _disposed=true;
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public int count() { return (_list.Count); }
        //----------------------------------------------------------
        public int add(TYPE item_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_root_list::add");
            //----------------------------------------------------------
            _list.Add(item_);
            int id = _list.IndexOf(item_);
            //----------------------------------------------------------
            (item_ as ccxiv_xxv_root)._id=id;
            (item_ as ccxiv_xxv_root)._parent=this;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (id);
            }
        //----------------------------------------------------------
        public TYPE gi(int index_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_root_list::gi");
            //----------------------------------------------------------
            if(index_>=_list.Count) { return (default(TYPE)); }
            TYPE item =_list[index_];
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (item);
            }
        //----------------------------------------------------------
        public void si(int index_, TYPE item_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_root_list::si");
            //----------------------------------------------------------
            while(index_>=_list.Count) { _list.Add(default(TYPE)); };
            _list[index_]=item_;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void reindex(Dictionary<int, int> indexes_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_root_list::reindex");
            //----------------------------------------------------------
            // Применяем полученные индексы
            //----------------------------------------------------------
            foreach(KeyValuePair<int, int> item in indexes_) {
                //----------------------------------------------------------
                bool found = false;
                for(int i = 0; (i<_list.Count)&&(!found); i++) {
                    if(_list[i]!=null) {
                        (_list[i] as ccxiv_xxv_root).reindex(item.Key, item.Value);
                        }
                    }
                //----------------------------------------------------------
                };
            //----------------------------------------------------------
            // Тестируем на предмет пересчёта
            //----------------------------------------------------------
            bool needrecalc = false;
            //----------------------------------------------------------
            for(int i = 0; (i<_list.Count)&&(!needrecalc); i++) {
                if(_list[i]!=null) {
                    ccxiv_xxv_root item = _list[i] as ccxiv_xxv_root;
                    needrecalc=!(i==(int)(item._id));
                    }
                }
            //----------------------------------------------------------
            xxv.log("needrecalc", needrecalc);
            //----------------------------------------------------------
            // Пересчёт
            //----------------------------------------------------------
            //!!ЗАГЛУШКА!!
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
