using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Linq;
using System.Text;
using System.Threading.Tasks;
//----------------------------------------------------------
namespace ccxiv_xxv {
    //----------------------------------------------------------
    class ccxiv_xxv_log {
        //----------------------------------------------------------
        public ccxiv_xxv_log _prev = null;
        //----------------------------------------------------------
        public ConsoleColor _color = ConsoleColor.White;
        private int _level = 0;
        private string _log_l = "";
        private string _log_r = "";
        //----------------------------------------------------------
        public ccxiv_xxv_log() {
            //----------------------------------------------------------
            xxv._color_rotate=(xxv._color_rotate>15)?1:(xxv._color_rotate+1);
            _color=(ConsoleColor)xxv._color_rotate;
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public ccxiv_xxv_log(ccxiv_xxv_log prev_, string maintag_, string funcname_) {
            //----------------------------------------------------------
            _color=prev_._color;
            _level=prev_._level+1;
            //----------------------------------------------------------
            int pid = System.Environment.ProcessId;
            int tid = System.Environment.CurrentManagedThreadId;
            //----------------------------------------------------------
            _log_l="["+pid+":"+tid+":"+maintag_+"]";
            for(int i = 0; i<_level; i++) { _log_l+="| "; }
            //----------------------------------------------------------
            _log_r=(" ("+funcname_+")");
            //----------------------------------------------------------
            _prev=prev_;
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public string format(string text_) {
            //----------------------------------------------------------
            return (_log_l+text_+_log_r);
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
