using System;
using System.Collections.Generic;
using System.Drawing;
using System.IO.Pipes;
using System.Linq;
using System.Reflection;
using System.Reflection.PortableExecutable;
using System.Text;
using System.Threading.Tasks;
using System.Xml.Linq;

using static System.Net.Mime.MediaTypeNames;
//----------------------------------------------------------
using ccxiv;
//----------------------------------------------------------
namespace ccxiv_xxv {
    //----------------------------------------------------------
    public class ccxiv_xxv_msg {
        //----------------------------------------------------------
        public enum type {
            //----------------------------------------------------------
            none = 0,
            bean = 1
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public enum com {
            //----------------------------------------------------------
            none = 0,
            ready = 1,
            manager_exec_child = 2,
            solder_updateme = 3,
            solder_update = 4,
            tenet_universe_update = 5,
            tenet_spirit_anima_done = 6
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vsize _sender_id = new(9999);
        public vsize _recipient_id = new(-1);
        public type _type = type.none;
        public com _com = com.none;
        public vbean _param=new vundef();
        //----------------------------------------------------------
        public ccxiv_xxv_msg() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_msg::new");
            //----------------------------------------------------------
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void read(vmem mem_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_msg::read(vmem)");
            //----------------------------------------------------------
            using(MemoryStream stream = new(mem_._value)) { read(stream); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void read(MemoryStream stream_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_msg::read(MemoryStream)");
            //----------------------------------------------------------
            using(BinaryReader reader = new(stream_)) { read(reader); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void read(BinaryReader reader_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_msg::read(BinaryReader)");
            //----------------------------------------------------------
            // Тип сообщения
            //----------------------------------------------------------
            vsize msg_type = new();
            msg_type.read(reader_);
            _type=(type)(int)msg_type;
            //----------------------------------------------------------
            switch(_type) {
                //----------------------------------------------------------
                case (type.none): { xxv.log("NONE"); break; }
                //----------------------------------------------------------
                case (type.bean): {
                        //----------------------------------------------------------
                        _sender_id.read(reader_);
                        //xxv.log("_sender_id", _sender_id);
                        //----------------------------------------------------------
                        _recipient_id.read(reader_);
                        //xxv.log("_recipient_id", _recipient_id);
                        //----------------------------------------------------------
                        vsize com_bean = new();
                        com_bean.read(reader_);
                        _com=(com)(int)com_bean;
                        //xxv.log("_com", _com);
                        //----------------------------------------------------------
                        _param=vbean.polymorph_read(reader_);
                        //xxv.log("_param", _param);
                        //----------------------------------------------------------
                        break;
                        //----------------------------------------------------------
                        }
                //----------------------------------------------------------
                default: { xxv.warn(1==1, "Unknown msg_type", msg_type); break; }
                    //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void write(vmem mem_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_msg::write(vmem)");
            //----------------------------------------------------------
            using(MemoryStream stream = new(mem_._value)) { write(stream); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void write(MemoryStream stream_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_msg::write(MemoryStream)");
            //----------------------------------------------------------
            using(BinaryWriter writer = new(stream_)) { write(writer); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void write(BinaryWriter writer_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_msg::write(BinaryWriter)");
            //----------------------------------------------------------
            // Тип сообщения
            //----------------------------------------------------------
            vsize type_bean = new((int)_type);
            type_bean.write(writer_);
            //----------------------------------------------------------
            switch(_type) {
                //----------------------------------------------------------
                case (type.none): { xxv.log("NONE"); break; }
                //----------------------------------------------------------
                case (type.bean): {
                        //----------------------------------------------------------
                        _sender_id.write(writer_);
                        //----------------------------------------------------------
                        _recipient_id.write(writer_);
                        //----------------------------------------------------------
                        vsize com_bean = new((int)_com);
                        com_bean.write(writer_);
                        //----------------------------------------------------------
                        _param.write(writer_);
                        //----------------------------------------------------------
                        break;
                        //----------------------------------------------------------
                        }
                //----------------------------------------------------------
                default: { xxv.warn(1==1, "Wrong _type", _type); break; }
                    //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vsize sizecalc() {
            //----------------------------------------------------------
            vsize size = 0;
            //----------------------------------------------------------
            vsize type_bean = new((int)_type);
            size+=type_bean.sizecalc();
            //----------------------------------------------------------
            switch(_type) {
                //----------------------------------------------------------
                case (type.bean): {
                        //----------------------------------------------------------
                        size+=_sender_id.sizecalc();
                        //----------------------------------------------------------
                        size+=_recipient_id.sizecalc();
                        //----------------------------------------------------------
                        vsize com_bean = new((int)_com);
                        size+=com_bean.sizecalc();
                        //----------------------------------------------------------
                        size+=_param.sizecalc();
                        //----------------------------------------------------------
                        break;
                        //----------------------------------------------------------
                        }
                }
            //----------------------------------------------------------
            return (size);
            }
        //----------------------------------------------------------
        public override string ToString() {
            //----------------------------------------------------------
            string text = ".msg("+_com.ToString()+","+_sender_id+","+_recipient_id+","+_param.ToString()+")";
            //----------------------------------------------------------
            return (text);
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
