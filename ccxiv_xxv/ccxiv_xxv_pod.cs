using System.Xml.Linq;

using static System.Net.Mime.MediaTypeNames;
//----------------------------------------------------------
using ccxiv;
//----------------------------------------------------------
namespace ccxiv_xxv {
    //----------------------------------------------------------
    public class ccxiv_xxv_pod {
        //----------------------------------------------------------
        public ccxiv_xxv_pod() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_pod::new");
            //----------------------------------------------------------
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public ccxiv_xxv_msg recv_msg(BinaryReader stream_reader_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_pod::recv_msg");
            //----------------------------------------------------------
            vmem mem = new();
            recv(stream_reader_,mem);
            //----------------------------------------------------------
            ccxiv_xxv_msg msg = new();
            msg.read(mem);
            //----------------------------------------------------------
            xxv.log("RECV msg", msg);
            xxv.fexit();
            //----------------------------------------------------------
            return (msg);
            }
        //----------------------------------------------------------
        public void recv(BinaryReader stream_reader_, vmem mem_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_pod::recv");
            //----------------------------------------------------------
            // (Синхронизация чтения)
            //----------------------------------------------------------
            xxv.log("SYNC");
            int code = -1;
            do { code=stream_reader_.Read(); } while(code<0);
            //----------------------------------------------------------
            // Читаем
            //----------------------------------------------------------
            mem_.read(stream_reader_,true,code);
            //----------------------------------------------------------
            xxv.log("RECV mem_", mem_);
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void send_msg(BinaryWriter stream_writer_, ccxiv_xxv_msg msg_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_pod::send_msg");
            //----------------------------------------------------------
            vmem mem = new(msg_.sizecalc());
            msg_.write(mem);
            //----------------------------------------------------------
            xxv.log("SEND mem", mem);
            send(stream_writer_, mem);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void send(BinaryWriter stream_writer_, vmem mem_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_pod::send");
            xxv.log("SEND mem_", mem_);
            //----------------------------------------------------------
            mem_.write(stream_writer_);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
