using System;
using System.Reflection;
//----------------------------------------------------------
using ccxiv;
//----------------------------------------------------------
namespace ccxiv_xxv {
    //----------------------------------------------------------
    public class ccxiv_xxv_root : IDisposable {
        //----------------------------------------------------------
        public object _parent = null;
        public vsize _uid = new(0);
        public vsize _id = new(0);
        public bool _disposed = false;
        //----------------------------------------------------------
        public ccxiv_xxv_root() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_root::ccxiv_xxv_root()");
            //----------------------------------------------------------
            _uid=xxv.uid();
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public ccxiv_xxv_root(object parent_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_root::ccxiv_xxv_root(parent)");
            //----------------------------------------------------------
            _parent=parent_;
            _uid=xxv.uid();
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            _disposed=true;
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public bool reindex(vsize uid_, vsize id_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_root::reindex");
            //----------------------------------------------------------
            if(_uid==uid_) { _id=id_; return (true); } else { return (false); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
