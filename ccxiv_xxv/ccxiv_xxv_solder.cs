using System;
using System.Diagnostics;
using System.IO;
using System.IO.Pipes;
using System.Reflection;
//----------------------------------------------------------
using ccxiv;
//----------------------------------------------------------
namespace ccxiv_xxv {
    //----------------------------------------------------------
    public class ccxiv_xxv_solder : IDisposable {
        //----------------------------------------------------------
        public string _name;
        public string _binfn;
        public string _binpath;
        //----------------------------------------------------------
        public bool _disposed = false;
        private BinaryReader _stream_reader;
        private BinaryWriter _stream_writer;
        //----------------------------------------------------------
        public vsize _id=new();
        public vsize _manager_id=new(-1);
        public vsize _parent_id=new(-1);
        //----------------------------------------------------------
        public ccxiv_xxv_solder(string name_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_solder::new(string)");
            xxv.log("name_",name_);
            //----------------------------------------------------------
            _name=name_;
            //----------------------------------------------------------
            ProcessModule binpm = Process.GetCurrentProcess().MainModule;
            _binfn=Path.GetFullPath(binpm.FileName);
            _binpath=Path.GetDirectoryName(_binfn);
            //----------------------------------------------------------
            xxv._datapath=xxv._workpath+@"\data";
            xxv._userpath=xxv._workpath+@"\userdata";
            //----------------------------------------------------------
            xxv.log("_binfn", _binfn);
            xxv.log("_binpath", _binpath);
            xxv.log("_workpath", xxv._workpath);
            xxv.log("_datapath", xxv._datapath);
            xxv.log("_userpath", xxv._userpath);
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                _stream_reader.Dispose();
                _stream_writer.Dispose();
                }
            //----------------------------------------------------------
            _disposed=true;
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public virtual void process_msg(ccxiv_xxv_msg msg_) {            }
        //----------------------------------------------------------
        public ccxiv_xxv_msg recv() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_solder::recv");
            //----------------------------------------------------------
            ccxiv_xxv_pod pod = new();
            ccxiv_xxv_msg msg = pod.recv_msg(_stream_reader);
            //----------------------------------------------------------
            xxv.log("RECV", msg);
            //----------------------------------------------------------
            process_msg(msg);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (msg);
            }
        //----------------------------------------------------------
        public void send(ccxiv_xxv_msg msg_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_solder::send(msg)");
            xxv.log("SEND msg_", msg_);
            //----------------------------------------------------------
            ccxiv_xxv_pod pod = new();
            pod.send_msg(_stream_writer,msg_);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void send(vsize recipient_id_, ccxiv_xxv_msg.com com_, vbean bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_solder::send(vsize,com,bean)");
            //----------------------------------------------------------
            ccxiv_xxv_msg msg = new();
            msg._sender_id=_id;
            msg._recipient_id=recipient_id_;
            msg._type=ccxiv_xxv_msg.type.bean;
            msg._com=com_;
            msg._param=bean_;
            //----------------------------------------------------------
            xxv.log("SEND msg",msg);
            //----------------------------------------------------------
            send(msg);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void send(ccxiv_xxv_msg.com com_, vbean bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_solder::send(com,bean)");
            //----------------------------------------------------------
            send(_manager_id,com_,bean_);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void send(ccxiv_xxv_msg.com com_, string text_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_solder::send(com,string)");
            xxv.log("SEND", com_+" "+text_);
            //----------------------------------------------------------
            vtext bean = new(text_);
            send(com_,bean);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void send_parent(ccxiv_xxv_msg.com com_, vbean bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_solder::send_parent(com,bean)");
            //----------------------------------------------------------
            send(_parent_id, com_, bean_);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void pipe_in_stream(PipeStream pipe_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_solder::pipe_in_stream");
            //----------------------------------------------------------
            _stream_reader=new(pipe_);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void pipe_out_stream(PipeStream pipe_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_solder::pipe_out_stream");
            //----------------------------------------------------------
            _stream_writer=new(pipe_);
            //_pipe_out_stream.AutoFlush=true;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
