using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO.Pipes;
using System.Reflection;
using System.Threading;
using System.Xml.Linq;
//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;
using ccxiv_xxv_tenet;
//----------------------------------------------------------
namespace ccxiv_xxv_helloscroll {
    //----------------------------------------------------------
    class Program {
        //----------------------------------------------------------
        static public ccxiv_xxv_solder_client _solder;
        static public ccxiv_xxv_helloscroll_replica _replica=new();
        //----------------------------------------------------------
        static void Main(string[] args_) {
            //----------------------------------------------------------
            xxv.maintag("HS");
            xxv.fenter("Program::Main");
            xxv.linebreak();
            xxv.log("start", args_);
            //----------------------------------------------------------
            try {
                //----------------------------------------------------------
                xxv.fenter("Program::Main try");
                //----------------------------------------------------------
                using(_solder = new("ccxiv_xxv_helloscroll", args_)) {
                    //----------------------------------------------------------
                    // Подключаем tenet_plain
                    //----------------------------------------------------------
                    _solder.send(ccxiv_xxv_msg.com.manager_exec_child, "ccxiv_xxv_tenet_plain");
                    //----------------------------------------------------------
                    // Основной цикл
                    //----------------------------------------------------------
                    xxv.linebreak();
                    xxv.log("start cycle");
                    bool _isexit = false;
                    //----------------------------------------------------------
                    do {
                        //----------------------------------------------------------
                        ccxiv_xxv_msg msg=_solder.recv();
                        xxv.log("RECV msg",msg);
                        process_msg(msg);
                        //----------------------------------------------------------
                        } while(!_isexit);
                    //----------------------------------------------------------
                    }
                //----------------------------------------------------------
                xxv.fexit();
                //----------------------------------------------------------
                } catch(Exception e) {
                //----------------------------------------------------------
                xxv.exception("HELLOSCROLL", e);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.linebreak();
            xxv.log("DEAD");
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void process_msg(ccxiv_xxv_msg msg_) {
            //----------------------------------------------------------
            xxv.fenter("Program::process_msg");
            //----------------------------------------------------------
            switch(msg_._com) {
                //----------------------------------------------------------
                case (ccxiv_xxv_msg.com.ready): { process_ready(msg_);  break; }
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public static void process_ready(ccxiv_xxv_msg msg_) {
            //----------------------------------------------------------
            xxv.fenter("Program::process_ready");
            //----------------------------------------------------------
            string name = (string)(msg_._param as vtext);
            xxv.log("name",name);
            //----------------------------------------------------------
            if(name=="ccxiv_xxv_tenet_plain") {
                //----------------------------------------------------------
                _replica._tenet_id=msg_._sender_id;
                _replica._tenet_ready=true;
                _replica.init();
                _replica.send_universe_update(_solder);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
