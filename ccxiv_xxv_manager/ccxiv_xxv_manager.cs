using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO.Pipes;
using System.Reflection;
using System.Threading;
using System.Xml.Linq;
//----------------------------------------------------------
namespace ccxiv {
    //----------------------------------------------------------
    class Program {
        //----------------------------------------------------------
        static ccxiv_xxv_list<ccxiv_xxv_manager_module> _modules = new();
        //----------------------------------------------------------
        static void Main(string[] args_) {
            //----------------------------------------------------------
            xxv.maintag("M");
            xxv.fenter("Main");
            xxv.linebreak();
            xxv.log("start", args_);
            //----------------------------------------------------------
            ConsoleKeyInfo keyboard;
            //----------------------------------------------------------
            try {
                //----------------------------------------------------------
                xxv.fenter("try");
                //----------------------------------------------------------
                // Первый модуль - сам менеджер
                //----------------------------------------------------------
                ccxiv_xxv_manager_module module0 = new("ccxiv_xxv_manager", false);
                module_start(module0);
                do { Thread.Sleep(300); } while(!module0._ispipeready);
                //----------------------------------------------------------
                using(ccxiv_xxv_solder manager_solder = new("ccxiv_xxv_manager", module0._pipe_in_key, module0._pipe_out_key)) {
                    //----------------------------------------------------------
                    // Теперь список обычных модулей
                    //----------------------------------------------------------
                    ccxiv_xxv_manager_module module1 = new("ccxiv_xxv_helloscroll");
                    module_start(module1);
                    //----------------------------------------------------------
                    // Цикл
                    //----------------------------------------------------------
                    xxv.linebreak();
                    xxv.log("ESC - exit");
                    do { keyboard=Console.ReadKey(true); } while(keyboard.Key!=ConsoleKey.Escape);
                    //----------------------------------------------------------
                    xxv.fexit();
                    //----------------------------------------------------------
                    }
                //----------------------------------------------------------
                } catch(Exception e) {
                //----------------------------------------------------------
                xxv.exception("MANAGER", e);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.linebreak();
            xxv.log("DEAD. Press ESC");
            do { keyboard=Console.ReadKey(true); } while(keyboard.Key!=ConsoleKey.Escape);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        private static void module_start(ccxiv_xxv_manager_module module_) {
            //----------------------------------------------------------
            xxv.fenter("module_start");
            //----------------------------------------------------------
            _modules.add(module_);
            //----------------------------------------------------------
            Thread thread = new(module_main);
            thread.Start(module_);
            xxv.log("thread.ManagedThreadId", thread.ManagedThreadId);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        private static void module_main(object obj_) {
            //----------------------------------------------------------
            xxv.fenter("module_main");
            //----------------------------------------------------------
            ccxiv_xxv_manager_module module = (ccxiv_xxv_manager_module)obj_;
            xxv.log("module._name", module._name);
            //----------------------------------------------------------
            using(module._solder= new(module._name)) {
                //----------------------------------------------------------
                xxv.log("start server pipes");
                //----------------------------------------------------------
                using(AnonymousPipeServerStream pipe_in = new(PipeDirection.In, HandleInheritability.Inheritable)) {
                    //----------------------------------------------------------
                    xxv.log("pipe_in.TransmissionMode", pipe_in.TransmissionMode);
                    module._pipe_in_key=pipe_in.GetClientHandleAsString();
                    xxv.log("module._pipe_in_key", module._pipe_in_key);
                    module._solder.pipe_in_stream(pipe_in);
                    //----------------------------------------------------------
                    using(AnonymousPipeServerStream pipe_out = new(PipeDirection.Out, HandleInheritability.Inheritable)) {
                        //----------------------------------------------------------
                        xxv.log("pipe_out.TransmissionMode", pipe_out.TransmissionMode);
                        module._pipe_out_key=pipe_out.GetClientHandleAsString();
                        xxv.log("module._pipe_out_key", module._pipe_out_key);
                        module._solder.pipe_out_stream(pipe_out);
                        //----------------------------------------------------------
                        module._solder._is_pipe_ready=true;
                        //----------------------------------------------------------
                        if(module._isexec) {
                            //----------------------------------------------------------
                            module_exec(module);
                            //----------------------------------------------------------
                            } else {
                            //----------------------------------------------------------
                            module_cycle(module);
                            //----------------------------------------------------------
                            }
                        //----------------------------------------------------------
                        }
                    //----------------------------------------------------------
                    }
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        private static void module_exec(ccxiv_xxv_manager_module module_) {
            //----------------------------------------------------------
            xxv.fenter("module_exec");
            //----------------------------------------------------------
            string exe_fn = module_._name+".exe";
            xxv.log("exe_fn", exe_fn);
            //----------------------------------------------------------
            string pipekey = (module_._pipe_in_key+" "+module_._pipe_out_key);
            //----------------------------------------------------------
            Process process = new();
            process.StartInfo.FileName=exe_fn;
            process.StartInfo.Arguments=pipekey;
            process.Start();
            xxv.log("process.Id", process.Id);
            //----------------------------------------------------------
            module_cycle(module_);
            //----------------------------------------------------------
            process.WaitForExit();
            process.Close();
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        private static void module_cycle(ccxiv_xxv_manager_module module_) {
            //----------------------------------------------------------
            xxv.fenter("module_cycle");
            //----------------------------------------------------------
            do {
                //----------------------------------------------------------
                ccxiv_xxv_msg msg=module_._solder.pipe_recv();
                msg._sender=module_._id;
                //----------------------------------------------------------
                if(msg._recipient<0) {
                    //----------------------------------------------------------
                    process_msg(msg);
                    //----------------------------------------------------------
                    } else {
                    //----------------------------------------------------------
                    ccxiv_xxv_manager_module module_recipient = _modules.get(msg._recipient);
                    //----------------------------------------------------------
                    }
                //----------------------------------------------------------
                } while(1==1);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        private static void process_msg(ccxiv_xxv_msg msg_) {
            //----------------------------------------------------------
            xxv.fenter("process_msg");
            //----------------------------------------------------------
            xxv.log("msg_._com", msg_._com);
            //----------------------------------------------------------
            switch(msg_._com) {
                //----------------------------------------------------------
                case (ccxiv_xxv_msg.com.manager_exec_child): {
                        //----------------------------------------------------------
                        string msg_text =msg_.data_read_text();
                        //----------------------------------------------------------
                        break;
                        //----------------------------------------------------------
                        }
                    //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
    //----------------------------------------------------------
    }
