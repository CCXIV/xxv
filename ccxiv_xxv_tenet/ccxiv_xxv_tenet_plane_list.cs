using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_plane_list : ccxiv_xxv_root_list<ccxiv_xxv_tenet_plane> {
        //----------------------------------------------------------
        private ccxiv_xxv_tenet_universe _universe_ptr = null;
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_plane_list(ccxiv_xxv_tenet_universe universe_ptr_) : base() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plane_list::new");
            //----------------------------------------------------------
            _universe_ptr=universe_ptr_;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                foreach(ccxiv_xxv_tenet_plane plane in _list) { plane.Dispose(); };
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vlist bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plane_list::bean_write");
            //----------------------------------------------------------
            vlist bean = new();
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plane plane in _list) { bean.add(plane.bean_write()); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vlist bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plane_list::bean_read");
            //----------------------------------------------------------
            for(int i=0;i<bean_.count();i++) {
                //----------------------------------------------------------
                ccxiv_xxv_tenet_plane plane = new(_universe_ptr);
                plane.bean_read(bean_[i] as vhash);
                si((int)plane._id,plane);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
