using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_world : ccxiv_xxv_root {
        //----------------------------------------------------------
        bool _visible=true;
        public ccxiv_xxv_tenet_box _box = new();
        public ccxiv_xxv_tenet_plane_list _planes = null;
        private ccxiv_xxv_tenet_universe _universe_ptr = null;
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_world(ccxiv_xxv_tenet_universe universe_ptr_) : base() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_world::new");
            //----------------------------------------------------------
            _universe_ptr=universe_ptr_;
            _planes=new(_universe_ptr);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                _box.Dispose();
                _planes.Dispose();
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vhash bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_world::bean_write");
            //----------------------------------------------------------
            vhash bean = new();
            bean["id"]=_id;
            bean["visible"]=new vsize(_visible);
            bean["planes"]=_planes.bean_write();
            bean["box"]=_box.bean_write();
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vhash bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_world::bean_read");
            //----------------------------------------------------------
            _id=bean_["id"] as vsize;
            _visible=(bool)(bean_["visible"] as vsize);
            _planes.bean_read(bean_["planes"] as vlist);
            _box.bean_read(bean_["box"] as vhash);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
