using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_spirit_list : ccxiv_xxv_root_list<ccxiv_xxv_tenet_spirit> {
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_spirit_list() : base() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_spirit_list::new");
            //----------------------------------------------------------
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                foreach(ccxiv_xxv_tenet_spirit spirit in _list) { spirit.Dispose(); };
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vlist bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_spirit_list::bean_write");
            //----------------------------------------------------------
            vlist bean = new();
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_spirit spirit in _list) { bean.add(spirit.bean_write()); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vlist bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_spirit_list::bean_read");
            //----------------------------------------------------------
            for(int i=0;i<bean_.count();i++) {
                //----------------------------------------------------------
                ccxiv_xxv_tenet_spirit spirit = new();
                spirit.bean_read(bean_[i] as vhash);
                //----------------------------------------------------------
                si((int)spirit._id,spirit);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
