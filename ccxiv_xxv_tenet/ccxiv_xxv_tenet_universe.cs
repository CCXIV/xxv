using System;
using System.Collections;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_universe : ccxiv_xxv_root {
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_texture_list _textures = new();
        public ccxiv_xxv_tenet_program_list _programs = new();
        public ccxiv_xxv_tenet_world_list _worlds = null;
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_universe() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_universe::new");
            //----------------------------------------------------------
            _worlds=new(this);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                _worlds.Dispose();
                _programs.Dispose();
                _textures.Dispose();
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vhash bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_universe::bean_write");
            //----------------------------------------------------------
            vhash bean = new();
            bean["id"]=_id;
            bean["worlds"]=_worlds.bean_write();
            bean["programs"]=_programs.bean_write();
            bean["textures"]=_textures.bean_write();
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vhash bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_universe::bean_read");
            //----------------------------------------------------------
            _id=bean_["id"] as vsize;
            _worlds.bean_read(bean_["worlds"] as vlist);
            _programs.bean_read(bean_["programs"] as vlist);
            _textures.bean_read(bean_["textures"] as vlist);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
