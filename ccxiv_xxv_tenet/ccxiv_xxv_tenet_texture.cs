using System;
using System.Collections.Generic;
using System.Linq;
using System.Numerics;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_texture : ccxiv_xxv_root {
        //----------------------------------------------------------
        public vtext _name = new();
        public vtext _sfn = new();
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_texture() : base() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_texture::new");
            //----------------------------------------------------------
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vhash bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_texture::bean_write");
            //----------------------------------------------------------
            vhash bean = new();
            bean["id"]=_id;
            bean["name"]=_name;
            bean["sfn"]=_sfn;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vhash bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_texture::bean_read");
            //----------------------------------------------------------
            _id=bean_["id"] as vsize;
            _name=bean_["name"] as vtext;
            _sfn=bean_["sfn"] as vtext;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
