using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;
using ccxiv_xxv_tenet;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet_plain {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_plain_spirit_list : ccxiv_xxv_root_list<ccxiv_xxv_tenet_plain_spirit> {
        //----------------------------------------------------------
        private ccxiv_xxv_tenet_plain_plane _plane_ptr = null;
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_plain_spirit_list(ccxiv_xxv_tenet_plain_plane plane_ptr_) : base() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_spirit_list::new");
            //----------------------------------------------------------
            _plane_ptr=plane_ptr_;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                foreach(ccxiv_xxv_tenet_plain_spirit spirit in _list) { spirit.Dispose(); };
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void opengl_init() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_spirit_list::opengl_init");
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plain_spirit spirit in _list) { spirit.opengl_init(); }
            //----------------------------------------------------------
            xxv.fexit();
            }
        //----------------------------------------------------------
        public void opengl_draw() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_spirit_list::opengl_draw");
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plain_spirit spirit in _list) { spirit.opengl_draw(); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vlist bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_spirit_list::bean_write");
            //----------------------------------------------------------
            vlist bean = new();
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plain_spirit spirit in _list) { bean.add(spirit.bean_write()); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vlist bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_spirit_list::bean_read");
            xxv.log("BEAN spirits count", bean_.count());
            //----------------------------------------------------------
            for(int i = 0; i<bean_.count(); i++) {
                //----------------------------------------------------------
                ccxiv_xxv_tenet_plain_spirit spirit = new(_plane_ptr);
                spirit.bean_read(bean_[i] as vhash);
                //----------------------------------------------------------
                si((int)spirit._id, spirit);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
