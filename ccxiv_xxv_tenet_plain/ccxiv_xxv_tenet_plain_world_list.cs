//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;
using ccxiv_xxv_tenet;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet_plain {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_plain_world_list : ccxiv_xxv_root_list<ccxiv_xxv_tenet_plain_world> {
        //----------------------------------------------------------
        private ccxiv_xxv_tenet_plain_universe _universe_ptr = null;
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_plain_world_list(ccxiv_xxv_tenet_plain_universe universe_ptr_) : base() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world_list::new");
            //----------------------------------------------------------
            _universe_ptr=universe_ptr_;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                foreach(ccxiv_xxv_tenet_plain_world world in _list) { world.Dispose(); }
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void opengl_init() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world_list::opengl_init");
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plain_world world in _list) { world.opengl_init(); }
            //----------------------------------------------------------
            xxv.fexit();
            }
        //----------------------------------------------------------
        public void opengl_draw() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world_list::opengl_draw");
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plain_world world in _list) { world.opengl_draw(); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vlist bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world_list::bean_write");
            //----------------------------------------------------------
            vlist bean = new();
            foreach(ccxiv_xxv_tenet_plain_world world in _list) { bean.add(world.bean_write()); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vlist bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world_list::bean_read");
            xxv.log("BEAN worlds count", bean_.count());
            //----------------------------------------------------------
            for(int i = 0; i<bean_.count(); i++) {
                //----------------------------------------------------------
                ccxiv_xxv_tenet_plain_world world = new(_universe_ptr);
                world.bean_read(bean_[i] as vhash);
                si((int)world._id, world);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
