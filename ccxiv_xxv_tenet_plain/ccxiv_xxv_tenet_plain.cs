using System;
using System.Reflection;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;
using ccxiv_xxv_tenet;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet_plain {
    //----------------------------------------------------------
    class Program {
        //----------------------------------------------------------
        static public ccxiv_xxv_tenet_plain_window _window=null;
        //----------------------------------------------------------
        static void Main(string[] args_) {
            //----------------------------------------------------------
            xxv.maintag("TP");
            xxv.fenter("Program::Main");
            xxv.linebreak();
            xxv.log("start", args_);
            //----------------------------------------------------------
            try {
                //----------------------------------------------------------
                xxv.fenter("Program::Main try");
                //----------------------------------------------------------
                using(_window = new(args_)) {
                    //----------------------------------------------------------
                    // Тред, чтобы не паузить окно
                    //----------------------------------------------------------
                    thread_start();
                    //----------------------------------------------------------
                    // OPENGL
                    //----------------------------------------------------------
                    _window.Run();
                    //----------------------------------------------------------
                    }
                //----------------------------------------------------------
                xxv.fexit();
                //----------------------------------------------------------
                } catch(Exception e) {
                //----------------------------------------------------------
                xxv.exception("TENET_PLAIN", e);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.linebreak();
            xxv.log("DEAD");
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        private static void thread_start() {
            //----------------------------------------------------------
            xxv.fenter("Program::thread_start");
            //----------------------------------------------------------
            Thread thread = new(thread_cycle);
            thread.Start();
            xxv.log("thread.ManagedThreadId", thread.ManagedThreadId);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        private static void thread_cycle(object obj_) {
            //----------------------------------------------------------
            xxv.fenter("Program::thread_cycle");
            //----------------------------------------------------------
            _window._replica.thread_cycle(obj_);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
