using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;
using ccxiv_xxv_tenet;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet_plain {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_plain_plane_list : ccxiv_xxv_root_list<ccxiv_xxv_tenet_plain_plane> {
        //----------------------------------------------------------
        private ccxiv_xxv_tenet_plain_world _world_ptr = null;
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_plain_plane_list(ccxiv_xxv_tenet_plain_world world_ptr_) : base() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_plane_list::new");
            //----------------------------------------------------------
            _world_ptr=world_ptr_;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                foreach(ccxiv_xxv_tenet_plain_plane plane in _list) { plane.Dispose(); };
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void opengl_init() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_plane_list::opengl_init");
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plain_plane plane in _list) { plane.opengl_init(); }
            //----------------------------------------------------------
            xxv.fexit();
            }
        //----------------------------------------------------------
        public void opengl_draw() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_plane_list::opengl_draw");
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plain_plane plane in _list) { plane.opengl_draw(); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vlist bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_plane_list::bean_write");
            //----------------------------------------------------------
            vlist bean = new();
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plain_plane plane in _list) { bean.add(plane.bean_write()); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vlist bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_plane_list::bean_read");
            xxv.log("BEAN planes count", bean_.count());
            //----------------------------------------------------------
            for(int i = 0; i<bean_.count(); i++) {
                //----------------------------------------------------------
                ccxiv_xxv_tenet_plain_plane plane = new(_world_ptr);
                plane.bean_read(bean_[i] as vhash);
                si((int)plane._id, plane);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
