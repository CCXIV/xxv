using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;
using ccxiv_xxv_tenet;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet_plain {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_plain_world : ccxiv_xxv_root {
        //----------------------------------------------------------
        bool _visible = true;
        public ccxiv_xxv_tenet_box _box = new();
        public ccxiv_xxv_tenet_plain_plane_list _planes = null;
        public ccxiv_xxv_tenet_plain_universe _universe_ptr = null;
        public bool _opengl_ready = false;
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_plain_world(ccxiv_xxv_tenet_plain_universe universe_ptr_) : base(universe_ptr_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world::new");
            //----------------------------------------------------------
            _universe_ptr=universe_ptr_;
            _planes=new(this);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                _box.Dispose();
                _planes.Dispose();
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void opengl_init() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world::opengl_init");
            //----------------------------------------------------------
            _planes.opengl_init();
            _opengl_ready=true;
            //----------------------------------------------------------
            xxv.fexit();
            }
        //----------------------------------------------------------
        public void opengl_draw() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world::opengl_draw");
            //----------------------------------------------------------
            _planes.opengl_draw();
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public vhash bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world::bean_write");
            //----------------------------------------------------------
            vhash bean = new();
            bean["id"]=_id;
            bean["visible"]=new vsize(_visible);
            bean["planes"]=_planes.bean_write();
            bean["box"]=_box.bean_write();
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vhash bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_world::bean_read");
            //----------------------------------------------------------
            _id=bean_["id"] as vsize;
            _visible=(bool)(bean_["visible"] as vsize);
            _planes.bean_read(bean_["planes"] as vlist);
            _box.bean_read(bean_["box"] as vhash);
            //----------------------------------------------------------
            xxv.log("BEAN world _id", _id);
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
