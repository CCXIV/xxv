using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;
using ccxiv_xxv_tenet;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet_plain {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_plain_replica : IDisposable {
        //----------------------------------------------------------
        public bool _main_close = false;
        public ccxiv_xxv_tenet_plain_universe _universe = null;
        public ccxiv_xxv_solder_client _solder=null;
        private bool _disposed = false;
        private vsize _master_id = -1;
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_plain_replica(string[] args_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_replica::new");
            //----------------------------------------------------------
            _solder=new("ccxiv_xxv_tenet_plain", args_);
            _universe=new(this);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                _main_close=true;
                //----------------------------------------------------------
                _universe.Dispose();
                if(_solder!=null) { _solder.Dispose(); }
                //----------------------------------------------------------
                }
            _disposed=true;
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void opengl_tick() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_replica::tick");
            //----------------------------------------------------------
            _universe.opengl_tick();
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void opengl_draw() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_replica::opengl_draw");
            //----------------------------------------------------------
            _universe.opengl_draw(); 
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void thread_cycle(object obj_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_replica::thread_cycle");
            //----------------------------------------------------------
            xxv.linebreak();
            xxv.log("start cycle");
            bool _isexit = false;
            //----------------------------------------------------------
            do {
                //----------------------------------------------------------
                ccxiv_xxv_msg msg = _solder.recv();
                xxv.log("RECV msg", msg);
                process_msg(msg);
                //----------------------------------------------------------
                } while((!_isexit)||(!_main_close));
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void process_msg(ccxiv_xxv_msg msg_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_replica::process_msg");
            //----------------------------------------------------------
            switch(msg_._com) {
                //----------------------------------------------------------
                case (ccxiv_xxv_msg.com.tenet_universe_update): { process_universe_update(msg_); break; }
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void process_universe_update(ccxiv_xxv_msg msg_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_replica::process_universe_update");
            //----------------------------------------------------------
            _master_id=msg_._sender_id;
            _universe.bean_read(msg_._param as vhash);
            _universe._opengl_do_init=true;
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void send_spirit_anima_done(vbean bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_replica::send_universe_update");
            //----------------------------------------------------------
            _solder.send(_master_id, ccxiv_xxv_msg.com.tenet_spirit_anima_done, bean_);
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
