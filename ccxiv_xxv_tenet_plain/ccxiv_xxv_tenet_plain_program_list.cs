using System;
using System.Collections.Generic;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Threading.Tasks;

//----------------------------------------------------------
using ccxiv;
using ccxiv_xxv;
using ccxiv_xxv_tenet;

//----------------------------------------------------------
namespace ccxiv_xxv_tenet_plain {
    //----------------------------------------------------------
    public class ccxiv_xxv_tenet_plain_program_list : ccxiv_xxv_root_list<ccxiv_xxv_tenet_plain_program> {
        //----------------------------------------------------------
        public ccxiv_xxv_tenet_plain_program_list() : base() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_program_list::new");
            //----------------------------------------------------------
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void Dispose() {
            //----------------------------------------------------------
            if(!_disposed) {
                //----------------------------------------------------------
                foreach(ccxiv_xxv_tenet_plain_program program in _list) { program.Dispose(); };
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            base.Dispose();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        public void opengl_init() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_program_list::opengl_init");
            //----------------------------------------------------------
            foreach(ccxiv_xxv_tenet_plain_program program in _list) { program.opengl_init(); }
            //----------------------------------------------------------
            xxv.fexit();
            }
        //----------------------------------------------------------
        public vlist bean_write() {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_program_list::bean_write");
            //----------------------------------------------------------
            vlist bean = new();
            foreach(ccxiv_xxv_tenet_plain_program program in _list) { bean.add(program.bean_write()); }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            return (bean);
            }
        //----------------------------------------------------------
        public void bean_read(vlist bean_) {
            //----------------------------------------------------------
            xxv.fenter("ccxiv_xxv_tenet_plain_program_list::bean_read");
            xxv.log("BEAN programs count", bean_.count());
            //----------------------------------------------------------
            for(int i = 0; i<bean_.count(); i++) {
                //----------------------------------------------------------
                ccxiv_xxv_tenet_plain_program program = new();
                program.bean_read(bean_[i] as vhash);
                si((int)program._id, program);
                //----------------------------------------------------------
                }
            //----------------------------------------------------------
            xxv.fexit();
            //----------------------------------------------------------
            }
        //----------------------------------------------------------
        }
    //----------------------------------------------------------
    }
